-- JpaUserNotificationRepositoryInternalTest 专用建表（H2；与 V105 生产态对齐）
-- 实体注解 columnDefinition="jsonb" 为 PG 专属，H2 用 JSON 等价替代
DROP TABLE IF EXISTS sys_user_notification;

CREATE TABLE sys_user_notification (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id    BIGINT       NOT NULL,
    sender_user_id       BIGINT,
    sender_org_id        BIGINT,
    notification_type    VARCHAR(64)  NOT NULL,
    title                VARCHAR(255) NOT NULL,
    content              TEXT         NOT NULL,
    status               VARCHAR(32)  NOT NULL DEFAULT 'UNREAD',
    action_url           VARCHAR(500),
    related_entity_type  VARCHAR(64),
    related_entity_id    BIGINT,
    batch_key            VARCHAR(64),
    metadata_json        JSON,
    read_at              TIMESTAMP,
    created_at           TIMESTAMP    NOT NULL,
    updated_at           TIMESTAMP    NOT NULL
);
